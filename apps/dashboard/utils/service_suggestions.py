def normalize_category(raw_category):
    """Normalize user-entered or database category string into a standard key."""
    if not raw_category:
        return "unknown"
    cat = raw_category.lower()
    
    if any(x in cat for x in ["salon", "beauty", "spa", "hair"]):
        return "salon_beauty"
    if any(x in cat for x in ["health", "clinic", "medical", "doctor", "dentist"]):
        return "healthcare"
    if any(x in cat for x in ["fitness", "gym", "yoga", "training", "workout"]):
        return "fitness"
    if any(x in cat for x in ["education", "tutor", "class", "school", "teach"]):
        return "education"
    if any(x in cat for x in ["consult", "coach", "advisor", "strategy"]):
        return "consulting"
    if any(x in cat for x in ["home", "clean", "plumb", "electric", "pest"]):
        return "home_services"
    if any(x in cat for x in ["repair", "fix", "laptop", "mobile", "computer"]):
        return "repair"
    if any(x in cat for x in ["photo", "camera", "shoot", "studio"]):
        return "photography"
    if any(x in cat for x in ["auto", "car", "vehicle", "mechanic"]):
        return "automobile"
    if any(x in cat for x in ["profession", "legal", "lawyer", "accountant"]):
        return "professional"
        
    return "unknown"

def get_service_suggestions(category):
    """Return a list of suggested services for the given business category."""
    normalized = normalize_category(category)
    return SERVICE_SUGGESTIONS.get(normalized, [])

